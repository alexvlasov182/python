"""
Comparison Operators
== Equal
!= NotEqual
>= GreaterThan
<= LessThan
> GreaterThanOrEqual
< LessThanOrEqual
"""


print(2 == 3)
print(2 != 3)
print(2 < 3)
print(2 <= 3)
print(2 >= 3)
print(2 >= 3)

"""
Logical Operators
and
or
not
"""
print(2 <= 3 and 4 > 1)
print(4 > 7 or 1 == 1)
print(not (7 == 7))