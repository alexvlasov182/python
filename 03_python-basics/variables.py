"""
RULES for Variables!
  When naming variables there are some
  rules that must be followed:
- A variable name must start with a 
letter or the underscore character

- A variable name cannot start with a number

- A variable name can only contain alpha-numeric characters
and underscore (A-z, 0-9, and _)

- Variable names are case-sensitive
(age, Age and AGE are three different variables)
"""

examplevar = 'Python'
print(examplevar)

example_var = 'Python another variable'
print(example_var)

_example_var = 'Python another variable'
print(_example_var)

